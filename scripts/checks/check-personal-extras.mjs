import assert from 'node:assert/strict';
import {parseData} from '../../lib/companion.ts';
import {chatContext,currentState} from '../../lib/model.ts';
import {editStudyRecord} from '../../lib/study.ts';
const reading={title:'自定义书',author:'作者',progress:'第 52 页',thought:'喜欢这一段',updatedAt:new Date().toISOString()};
const record={at:new Date(2026,8,8,23).toISOString(),minutes:120,group:'数学'};
const data={name:'冬清',since:'2023-07-08',messages:[{who:'me',text:'你好'},{who:'luke',text:'收到一半',interrupted:true}],tasks:[],notes:[],checks:[],books:[reading],reading,focusLog:[record],contextSharing:{weather:false,reading:false,study:false,dates:false}};
assert.deepEqual(parseData(JSON.stringify(data)),data);
const payload=JSON.stringify(chatContext(data,'私有天气',new Date(2026,8,9)));
assert.doesNotMatch(payload,/私有天气|自定义书|第 52 页|2023-07-08/);
assert.equal(currentState({...data,contextSharing:{}},'',new Date()).reading.progress,'第 52 页');
const changed=editStudyRecord(data,record,'英语',new Date(2026,8,8,23,30).getTime(),new Date(2026,8,9,0,30).getTime(),new Date(2026,8,10).getTime());
assert.equal(changed.focusLog.length,2);assert.deepEqual(changed.focusLog.map(r=>[r.group,r.minutes]),[['英语',30],['英语',30]]);
assert.equal(data.focusLog[0],record);
assert.throws(()=>editStudyRecord(data,record,'英语',20,10));
assert.throws(()=>editStudyRecord(data,record,'英语',10,Date.now()+60000));
assert.throws(()=>editStudyRecord(data,{...record},'英语',10,20));
assert.throws(()=>parseData(JSON.stringify({...data,books:[{...reading,thought:'x'.repeat(1001)}]})));
assert.throws(()=>parseData(JSON.stringify({...data,contextSharing:{weather:'no'}})));
console.log('PASS: custom books/progress/interruption backup, sharing omitted from all context blocks, date-split edits, invalid/stale edits rejected');
